// ---- Switching designs (stage 9) -----------------------------------------------
Preferences prefs;                         // remembers the design across power cycles
int designIndex = 0;

void selectDesign(int i) {
    designIndex = i;
    eye = &designs[i];
    if (upRam && loRam) {                  // lid maps are read per pixel: keep them in RAM
        memcpy(upRam, eye->upper, S * S);
        memcpy(loRam, eye->lower, S * S);
        upMap = upRam; loMap = loRam;
    } else {
        upMap = reinterpret_cast<const uint8_t (*)[S]>(eye->upper);
        loMap = reinterpret_cast<const uint8_t (*)[S]>(eye->lower);
    }
    pupil.setRange(eye->irisMin, eye->irisMax);
}

// ---- Two-core pipeline (stage 7) ---------------------------------------------
// Core 1 (loop) renders frame N+1 while core 0 (pushTask) pushes frame N.
// Buffers travel through two queues, so neither core touches a buffer the
// other is using:  freeQ  = buffers ready to draw into (pusher -> renderer)
//                  readyQ = finished frames to push   (renderer -> pusher)
QueueHandle_t freeQ, readyQ;

// Pusher statistics: only pushTask writes them, only ever increasing; loop()
// reads them and takes differences, so the two cores never write the same word.
volatile uint32_t pushCount = 0, pushBusyUs = 0, pushWaitUs = 0;

void pushTask(void *) {
    for (;;) {
        uint16_t *buf;
        uint32_t t0 = micros();
        xQueueReceive(readyQ, &buf, portMAX_DELAY);    // wait for a finished frame
        uint32_t t1 = micros();
        panel.pushColors(0, 0, W, H, buf);
        uint32_t t2 = micros();
        xQueueSend(freeQ, &buf, portMAX_DELAY);        // hand the buffer back
        // Push is the bottleneck, so a frame is always waiting and this task never
        // blocks: IDLE0 starved and the task watchdog rebooted the chip every ~10 s.
        // Sleep one tick so IDLE0 runs. (Priority 0 instead halved push speed:
        // idle sleeps until the next tick each time it gets a turn.)
        vTaskDelay(1);
        pushWaitUs += t1 - t0;
        pushBusyUs += t2 - t1;
        pushCount++;
    }
}

void setup() {
    Serial.begin(115200);
    Serial.setTxTimeoutMs(0);   // G11 — not enough on core 2.0.17, hence logf()
    delay(1500);
    Serial.println("\n=== T-RGB stage 9: eight eye designs ===");

    panel.begin();
    for (auto &b : fbs) {
        b = (uint16_t *)ps_malloc(W * H * sizeof(uint16_t));
        if (!b) { Serial.println("ps_malloc failed"); return; }
    }
    fb = fbs[0];
    // Copy the per-pixel tables from flash into internal RAM.
    constexpr uint32_t CAPS = MALLOC_CAP_INTERNAL | MALLOC_CAP_8BIT;
    auto *texRam = (uint16_t (*)[S])heap_caps_malloc(sizeof(lidTex), CAPS);
    upRam = (uint8_t (*)[S])heap_caps_malloc(S * S, CAPS);
    loRam = (uint8_t (*)[S])heap_caps_malloc(S * S, CAPS);
    if (texRam) memcpy(texRam, lidTex, sizeof(lidTex));
    Serial.printf("RAM copies: texture %s, lid maps %s; internal RAM free %u\n",
                  texRam ? "ok" : "FAILED", upRam && loRam ? "ok" : "FAILED",
                  (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL));

    // Use the RAM copies (stage 6b benchmark, same frame: all flash 41.2 ms,
    // + texture in RAM 34.5 ms, + lid maps in RAM 29.4 ms per render).
    if (texRam) lid = texRam;

    // Last design used ("eye" namespace in NVS, key "design"; 0 = dragon if none).
    prefs.begin("eye", false);
    int saved = prefs.getUChar("design", 0);
    if (saved >= NUM_DESIGNS) saved = 0;
    selectDesign(saved);
    Serial.printf("design %d: %s\n", designIndex, eye->name);

    const int c = (eye->scleraSize - S) / 2;
    drawEye((eye->irisMin + eye->irisMax) / 2, c, c, 0, 0, 0);
    panel.pushColors(0, 0, W, H, fb);          // END coords — full frame
    panel.setBrightness(16);                   // after drawing (G21)

    // Start the pipeline: both buffers free, pusher on core 0 (loop runs on core 1).
    freeQ = xQueueCreate(2, sizeof(uint16_t *));
    readyQ = xQueueCreate(2, sizeof(uint16_t *));
    for (auto b : fbs) xQueueSend(freeQ, &b, 0);
    xTaskCreatePinnedToCore(pushTask, "push", 4096, nullptr, 2, nullptr, 0);
}

void loop() {
    static uint32_t totalFrames = 0, frames = 0, renderUs = 0, waitUs = 0, lastReport = millis();
    static uint32_t lastPushCount = 0, lastPushBusy = 0, lastPushWait = 0;

    static uint32_t moves = 0;
    static int fingerX = -1, fingerY = -1;    // last touch, for the log
    const uint32_t now = micros();
    int tx, ty;
    const bool touch = touched(tx, ty);
    if (touch) {
        pain.hurt(now);
        saccade.lookAt(now, fingerToEye(tx), fingerToEye(ty));
        fingerX = tx; fingerY = ty;
    }

    // Long press (stage 9): a finger down for 2 s switches to the next design, once
    // per press. "Down" ends after 200 ms without a touch report. The lids are
    // forced shut for SHUT_US, and the swap happens behind them.
    constexpr uint32_t LONG_PRESS_US = 2000000, SHUT_US = 250000;
    static bool fingerDown = false, switchedThisPress = false;
    static uint32_t downSince = 0, lastSeen = 0, shutStart = 0, switches = 0;
    if (touch) {
        if (!fingerDown) { fingerDown = true; switchedThisPress = false; downSince = now; }
        lastSeen = now;
    } else if (fingerDown && now - lastSeen > 200000) {
        fingerDown = false;
    }
    if (fingerDown && !switchedThisPress && now - downSince >= LONG_PRESS_US) {
        switchedThisPress = true;
        shutStart = now;
        switches++;
        selectDesign((designIndex + 1) % NUM_DESIGNS);
        prefs.putUChar("design", designIndex);   // a flash write: a few ms
    }
    const bool shut = switches && now - shutStart < SHUT_US;
    const float hurt = pain.level(now);        // 0 = calm .. 1 = in pain
    if (!pain.active) saccade.release(now);    // pain over: roam again
    int ex, ey;
    const bool wasMoving = saccade.moving;
    saccade.update(now, ex, ey);
    if (saccade.moving && !wasMoving) moves++;

    // Pupil shrinks to a pinpoint in pain (below IRIS_MIN = narrower than normal).
    constexpr int PINPOINT = 30;
    const int walk = pupil.update(now);
    const int iScale = walk + (PINPOINT - walk) * hurt;

    // 0..1023 -> sclera offset 0..SCLERA_SIZE-S (like Arduino's map()),
    // plus a tremble of up to +-6 rendered px while hurting.
    const int MAX_OFS = eye->scleraSize - S;   // 0 for the goat: it can't look around
    const int shake = 6 * hurt;
    int sx = ex * MAX_OFS / 1023, sy = ey * MAX_OFS / 1023;
    if (shake) {
        sx = constrain(sx + (int)random(-shake, shake + 1), 0, MAX_OFS);
        sy = constrain(sy + (int)random(-shake, shake + 1), 0, MAX_OFS);
    }

    uint8_t uT, lT;
    lids.update(now, sx, sy, shut ? 1.0f : pain.closure(now), uT, lT);
    const uint8_t tint = 20 * hurt;            // up to 20/32 of the way to red

    uint32_t t0 = micros();
    xQueueReceive(freeQ, &fb, portMAX_DELAY);  // a buffer the pusher is done with
    uint32_t t1 = micros();
    drawEye(iScale, sx, sy, uT, lT, tint);
    uint32_t t2 = micros();
    xQueueSend(readyQ, &fb, portMAX_DELAY);    // off to core 0

    frames++;
    waitUs += t1 - t0;
    renderUs += t2 - t1;
    if (millis() - lastReport >= 2000) {
        totalFrames += frames;
        const uint32_t pc = pushCount, pb = pushBusyUs, pw = pushWaitUs;   // snapshot
        const uint32_t pushes = max(1u, pc - lastPushCount);
        logf("t=%3lus %s(%lu) %.1f fps render %lu us (waited %lu) push %lu us  u %d l %d  "
             "touches %lu hurt %.2f %s finger %d,%d eye %d,%d kicks %lu (free %lu)\n",
             millis() / 1000, eye->name, (unsigned long)switches,
             frames * 1000.0f / (millis() - lastReport),
             (unsigned long)(renderUs / frames), (unsigned long)(waitUs / frames),
             (unsigned long)((pb - lastPushBusy) / pushes), uT, lT,
             (unsigned long)pain.touches, hurt, saccade.locked ? "GLARE" : "roam",
             fingerX, fingerY, ex, ey, (unsigned long)logKicks, (unsigned long)logStuckFree);
        lastPushCount = pc; lastPushBusy = pb; lastPushWait = pw;
        frames = renderUs = waitUs = 0;
        lastReport = millis();
    }
}
